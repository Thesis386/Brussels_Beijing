CJK = re.compile(r"[　-〿一-鿿＀-￯]")

# Punctuation that arrives from the source PDFs, and the few symbols the notes use.
PUNCT = [
    ("‘", "`"), ("’", "'"), ("“", "``"), ("”", "''"),
    ("–", "--"), ("—", "---"), ("…", r"\ldots{}"),
    (" ", " "), ("﻿", ""), ("→", "->"),
    ("§", r"\S{}"), ("€", r"\texteuro{}"),
]
SPECIALS = [
    ("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
    ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
    ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
]


def tex(s) -> str:
    """Escape a cell for LaTeX."""
    if pd.isna(s):
        return "---"
    s = str(s).strip()
    for bad, good in PUNCT:
        s = s.replace(bad, good)
    # Straight double quotes would typeset as closing quotes at both ends.
    s = re.sub(r'"([^"]*)"', r"``\1''", s)
    for bad, good in SPECIALS:
        s = s.replace(bad, good)
    return re.sub(r"\s+", " ", s).strip()


def emphasise(s: str) -> str:
    """Convert markdown emphasis to LaTeX. Must run *after* tex(), which escapes braces."""
    s = re.sub(r"\*\*([^*]+)\*\*", r"\\textbf{\1}", s)
    return re.sub(r"\*([^*]+)\*", r"\\emph{\1}", s)


def sort_key(t: str):
    return (t[0], int(re.match(r"[A-Z](\d+)", t).group(1)),
            float(t.split(".")[1]) if "." in t else 0)


def english(text: str, explicit: str | None, row) -> tuple[str, bool]:
    """Render one quoted passage in English, and say whether it was translated.

    Passages quoted from Chinese sources cannot be typeset under pdfLaTeX without a CJK
    package. The grounding record already carries an English rendering for each of them --
    either as an explicit '[Translation: ...]', or as a parenthetical gloss trailing the
    Chinese. Use that; never paraphrase one here.
    """
    if not CJK.search(text):
        return text, False

    if explicit is not None:
        out = explicit
    else:
        glosses = re.findall(r"\(([^()]*[A-Za-z]{3}[^()]*)\)", text)
        if not glosses:
            sys.exit(f"No English rendering for CJK quote on {row.topic_id} ({row.source}). "
                     f"Add a '[Translation: ...]' alongside it in issues_grounding.csv.")
        out = "; ".join(g.strip() for g in glosses)

    # Drop any residual CJK, e.g. a parenthetical gloss of a term inside the translation.
    out = re.sub(r"\s*\(\s*" + CJK.pattern + r"+\s*\)", "", out)
    out = CJK.sub("", out).strip()
    if not out:
        sys.exit(f"Empty rendering for CJK quote on {row.topic_id} ({row.source}).")
    return out, True


def split_passages(field: str) -> list[str]:
    """Split a quote field holding several passages joined as «..." and "...»."""
    if not field:
        return []
    return [p for p in re.split(r'"\s+and\s+"', field) if p.strip().strip('"').strip()]


def render_quotes(row) -> list[tuple[str, bool]]:
    """Return every quoted passage supporting this claim, as (quotation, is_translation).

    A claim is supported by up to two quote fields (quote_1, quote_2). Two adjustments
    keep the passage count honest, and the grounding report applies the same two:
    where quote_2 is a bracketed '[Translation: ...]' of quote_1 it is the rendering of
    quote_1, not a second quotation; and a single field holding several passages joined
    as «..." and "...» contributes one passage per passage.
    """
    q1 = "" if pd.isna(row.quote_1) else str(row.quote_1).strip()
    q2 = "" if pd.isna(row.quote_2) else str(row.quote_2).strip()

    m = re.match(r"\[\s*translation:\s*(.+?)\]\s*$", q2, flags=re.I | re.S)
    if m:
        return [english(q1, m.group(1), row)]

    out = []
    for field in (q1, q2):
        for passage in split_passages(field):
            out.append(english(passage, None, row))
    return out


