def a6_timing(model_key: str, pos_date: str) -> str:
    """A6 is not in the evidence-events file (it is an A-series baseline, not used in the
    correspondence test), so its timing line is derived from the model metadata here."""
    row = tmeta[tmeta.model_key == model_key].iloc[0]
    cutoff, release = row.knowledge_or_training_cutoff, row.release_date
    note = "A-series baseline, documented for completeness and not used in the correspondence test. "
    if pd.notna(cutoff) and str(pos_date) <= str(cutoff):
        return note + f"Predates the model's {cutoff} training cutoff."
    if str(pos_date) <= str(release):
        return note + f"Predates the {release} release."
    return note + f"Postdates the {release} release."


